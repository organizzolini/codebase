import { UPGRADE_DETAILS } from "./upgrade-dependencies.constants";

import type { SkippedStep } from "./upgrade-dependencies.types";

// 🌎 Utilities

/**
 * Writes the pull request the weekly job opens. Skipped steps lead the
 * summary and the details and close the body, where a reviewer cannot miss
 * them: a step that has been failing for weeks must not hide behind a pull
 * request that looks like any other.
 */
export function renderPullRequestBody(
  skipped: readonly SkippedStep[],
  workflowUrl: string,
): string {
  const summary = [
    "Automated toolchain updates detected by the weekly dependency check.",
    "Per-package npm and GitHub Actions bumps arrive separately, as their",
    "own Dependabot pull requests.",
    ...(skipped.length === 0
      ? []
      : [
          `⚠️ ${String(skipped.length)} upgrade step(s) were skipped; see Skipped Upgrades below.`,
        ]),
  ];
  const details = [
    ...skipped.map((step) => skippedBullet(step)),
    ...UPGRADE_DETAILS.map((detail) => `- ${detail}`),
  ];
  const sections = [
    ["## 🌰 Summary", summary.join("\n")],
    ["## 📝 Details", details.join("\n")],
    [
      "## 🧪 Testing",
      [
        "1. Review changes in the diff",
        "2. Verify all code checks pass",
        "3. Test functionality manually (if needed)",
      ].join("\n"),
    ],
    [
      "## 🔗 Related",
      `- *Generated by [🧑‍🚒 Upgrade Dependencies](${workflowUrl})*`,
    ],
  ].map(([heading, body]) => `${heading}\n\n${body}`);

  return `${[
    ...sections,
    ...(skipped.length === 0
      ? []
      : [
          [
            "## ⚠️ Skipped Upgrades",
            "These steps failed and were undone, so what they upgrade is missing from this pull request. The run carried on without them.",
            ...skipped.map((step) => quoteSkipped(step)),
          ].join("\n\n"),
        ]),
  ].join("\n\n")}\n`;
}

/** One skipped step's error, quoted in a collapsed block. */
function quoteSkipped(step: SkippedStep): string {
  return [
    "<details>",
    `<summary>${step.label} (exit ${String(step.exitCode)})</summary>`,
    "",
    "```text",
    step.tail.replaceAll("```", "'''"),
    "```",
    "",
    "</details>",
  ].join("\n");
}

/** The bullet a skipped step adds to the pull request's details. */
function skippedBullet(step: SkippedStep): string {
  return `- ⚠️ Skipped **${step.label}** (exit ${String(step.exitCode)}); it was undone. See Skipped Upgrades below.`;
}
