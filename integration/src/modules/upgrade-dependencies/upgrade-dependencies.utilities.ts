import {
  LINE_CHARACTERS,
  WARNING_LIMIT,
} from "./upgrade-dependencies.constants";

import type { Failure, StepReport } from "./upgrade-dependencies.types";

// 🌎 Utilities

/**
 * Writes the pull request the weekly job opens. Its details say what each step
 * came to, skipped steps first and in the summary, and close the body with
 * their errors and any warnings, where a reviewer cannot miss them: a step
 * that has been failing for weeks must not hide behind a pull request that
 * looks like any other.
 */
export function renderPullRequestBody(
  reports: readonly StepReport[],
  runUrl: string,
): string {
  const skipped = reports.flatMap((report) =>
    report.skipped === undefined
      ? []
      : [{ ...report.skipped, label: report.label }],
  );
  const warned = reports.filter((report) => report.warnings.length > 0);
  const summary = [
    "Automated toolchain updates detected by the weekly dependency check.",
    "Per-package npm and GitHub Actions bumps arrive separately, as their",
    "own Dependabot pull requests.",
    ...(skipped.length === 0
      ? []
      : [
          `⚠️ ${String(skipped.length)} upgrade step(s) were skipped; see Skipped Upgrades below.`,
        ]),
  ];
  const details = [
    ...skipped.map((failure) => skippedBullet(failure)),
    ...reports
      .filter((report) => report.skipped === undefined)
      .map((report) => detailBullet(report)),
  ];
  const sections = [
    ["## 🌰 Summary", summary.join("\n")],
    ["## 📝 Details", details.join("\n")],
    [
      "## 🧪 Testing",
      [
        "1. Review changes in the diff",
        "2. Verify all code checks pass",
        "3. Test functionality manually (if needed)",
      ].join("\n"),
    ],
    ["## 🔗 Related", `- *Generated by [🧑‍🚒 Upgrade Dependencies](${runUrl})*`],
  ].map(([heading, body]) => `${heading}\n\n${body}`);

  return `${[
    ...sections,
    ...(skipped.length === 0
      ? []
      : [
          [
            "## ⚠️ Skipped Upgrades",
            "These steps failed and were undone, so what they upgrade is missing from this pull request. The run carried on without them.",
            ...skipped.map((failure) => quoteSkipped(failure)),
          ].join("\n\n"),
        ]),
    ...(warned.length === 0
      ? []
      : [
          [
            "## ⚠️ Warnings",
            warned
              .flatMap((report) =>
                report.warnings.map(
                  (warning) => `- **${report.label}**: ${code(warning)}`,
                ),
              )
              .join("\n"),
          ].join("\n\n"),
        ]),
  ].join("\n\n")}\n`;
}

/** The distinct lines a step printed that begin with `⚠`. */
export function warningsOf(output: string): string[] {
  const lines = output
    .split("\n")
    .map((line) => line.trim())
    .filter((line) => line.startsWith("⚠"));

  return [...new Set(lines)].slice(0, WARNING_LIMIT);
}

/** Text as an inline code span, cut short, with backticks that would end it. */
function code(text: string): string {
  return `\`${text.slice(0, LINE_CHARACTERS).replaceAll("`", "'")}\``;
}

/** The bullet a step that ran adds to the pull request's details. */
function detailBullet({ changes, label, summary }: StepReport): string {
  const version = summary === undefined ? "" : `${summary}, `;

  return changes === ""
    ? `- ➖ **${label}**: already up to date${summary === undefined ? "" : ` (${summary})`}`
    : `- ✅ **${label}**: ${version}${changes}`;
}

/** One skipped step's error, quoted in a collapsed block. */
function quoteSkipped(failure: Failure): string {
  return [
    "<details>",
    `<summary>${failure.label} (exit ${String(failure.exitCode)})</summary>`,
    "",
    "```text",
    failure.tail.replaceAll("```", "'''"),
    "```",
    "",
    "</details>",
  ].join("\n");
}

/** The last line a failed step printed, which names why it failed. */
function reasonOf(tail: string): string {
  return tail.trim().split("\n").slice(-1).join("");
}

/** The bullet a skipped step adds to the pull request's details. */
function skippedBullet(failure: Failure): string {
  return `- ⚠️ **${failure.label}** skipped (exit ${String(failure.exitCode)}) and undone: ${code(reasonOf(failure.tail))}`;
}
